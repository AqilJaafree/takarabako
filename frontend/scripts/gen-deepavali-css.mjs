// Generates app/theme-deepavali.css from app/globals.css: every declaration
// that uses a red or brown (the lacquer, the dark warm surfaces, the muted
// ink) is repeated under [data-theme="deepavali"] with the colour turned
// purple, keeping its lightness, saturation and alpha. Golds, creams, greens,
// blues and the status reds (errors stay red) are left alone, so the gold
// accents carry over. Run it again after changing globals.css:
//
//   node scripts/gen-deepavali-css.mjs
//
// Hand-written Deepavali rules live in app/theme-deepavali-extra.css.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, "../app/globals.css");
const out = path.join(here, "../app/theme-deepavali.css");
const SCOPE = '[data-theme="deepavali"]';

// Colours that mean something (error, warning) keep their hue.
const KEEP = new Set(["ef7d6f", "ff8f86", "f09a5a", "239,125,111"]);
const PURPLE_HUE = 284;

function rgbToHsl(r, g, b) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  const l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h * 60, s, l];
}

function hslToRgb(h, s, l) {
  const k = (n) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return [f(0), f(8), f(4)].map((v) => Math.round(v * 255));
}

/// Reds and browns (hue under 30° or over 340°) become purple; the rest is null (unchanged).
function shift(r, g, b) {
  const [h, s, l] = rgbToHsl(r, g, b);
  if (s < 0.06 || !(h < 30 || h > 340)) return null;
  // Lift very dark surfaces a touch and saturate them, so they read as purple rather than black.
  const s2 = Math.min(1, l < 0.15 ? Math.max(s, 0.45) : s * 1.05);
  return hslToRgb(PURPLE_HUE, s2, l);
}

const hex2 = (n) => n.toString(16).padStart(2, "0");

function recolor(value) {
  let changed = false;
  const next = value
    .replace(/#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b/g, (m, hex) => {
      const full = hex.length === 3 ? [...hex].map((c) => c + c).join("") : hex;
      if (KEEP.has(full.toLowerCase())) return m;
      const rgb = shift(parseInt(full.slice(0, 2), 16), parseInt(full.slice(2, 4), 16), parseInt(full.slice(4, 6), 16));
      if (!rgb) return m;
      changed = true;
      return `#${rgb.map(hex2).join("")}`;
    })
    .replace(/rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)/g, (m, r, g, b, a) => {
      if (KEEP.has(`${r},${g},${b}`)) return m;
      const rgb = shift(+r, +g, +b);
      if (!rgb) return m;
      changed = true;
      return a === undefined ? `rgb(${rgb.join(", ")})` : `rgba(${rgb.join(", ")}, ${a})`;
    });
  return changed ? next : null;
}

function scopeSelector(sel) {
  const s = sel.trim();
  if (s.startsWith(":root")) return `:root${SCOPE}${s.slice(5)}`;
  if (/^html\b/.test(s)) return `html${SCOPE}${s.slice(4)}`;
  return `${SCOPE} ${s}`;
}

const root = postcss.parse(fs.readFileSync(src, "utf8"));
const result = postcss.root();
let count = 0;

root.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes/.test(rule.parent.name)) return;
  const decls = [];
  rule.each((node) => {
    if (node.type !== "decl") return;
    const v = recolor(node.value);
    if (v) decls.push(node.clone({ value: v }));
  });
  if (!decls.length) return;
  count += decls.length;
  const scoped = postcss.rule({ selectors: rule.selectors.map(scopeSelector) });
  decls.forEach((d) => scoped.append(d));
  // Keep the rule inside its @media, if it has one.
  let target = scoped;
  for (let p = rule.parent; p && p.type === "atrule"; p = p.parent) {
    target = postcss.atRule({ name: p.name, params: p.params }).append(target);
  }
  result.append(target);
});

const header = `/* GENERATED by scripts/gen-deepavali-css.mjs from globals.css: do not edit by hand.
   The Deepavali theme: reds and browns turned purple (${count} declarations). */\n`;
fs.writeFileSync(out, header + result.toString() + "\n");
console.log(`wrote ${path.relative(process.cwd(), out)}: ${count} declarations`);
